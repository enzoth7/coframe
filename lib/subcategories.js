// Devuelve el subrubro unificado o null si no hay traducción conocida.
export function toSubcategory(value, category, name) {
  if (SUBCATEGORY_NAMES.includes(value)) return value;
  if (BY_BRAND[name]) return BY_BRAND[name];
  if (category && category !== "Tecnología" && OLD[`${category}|${value}`]) return OLD[`${category}|${value}`];
  if (category === "Tecnología") return OLD[`${category}|${value}`] || "Software y servicios digitales";
  return null;
}
